/**
 * Generates dist/sw.js after the Astro build.
 *
 * She will open this on ship wifi and then walk around an island with no
 * signal, so we precache the whole site in one shot rather than caching
 * lazily as she browses — a page she never opened on wifi is a page she
 * cannot open ashore.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname;

/** Files that must never be precached. */
const EXCLUDE = new Set(['sw.js', 'robots.txt', 'sitemap-index.xml']);

const PRECACHE_EXT = new Set([
  '.html', '.css', '.js', '.woff2', '.svg', '.png', '.jpg', '.jpeg',
  '.webp', '.avif', '.ico', '.webmanifest', '.json',
]);

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

const files = await walk(DIST);

let bytes = 0;
const urls = [];
for (const f of files) {
  const rel = relative(DIST, f).split(sep).join('/');
  if (EXCLUDE.has(rel)) continue;
  const ext = rel.slice(rel.lastIndexOf('.'));
  if (!PRECACHE_EXT.has(ext)) continue;

  bytes += (await stat(f)).size;
  // Serve /santorini/index.html at the clean URL she'll actually visit.
  urls.push(rel === 'index.html' ? '/' : '/' + rel.replace(/\/index\.html$/, ''));
  if (rel.endsWith('/index.html') || rel === 'index.html') urls.push('/' + rel);
}

// Content-addressed version: the cache only churns when something really changed.
const hash = createHash('sha256');
for (const f of files.sort()) hash.update(await readFile(f));
const version = hash.digest('hex').slice(0, 12);

const manifest = [...new Set(urls)].sort();

const sw = `/* Generated by scripts/build-sw.mjs — do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'liv-' + VERSION;
const PRECACHE = ${JSON.stringify(manifest, null, 0)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      // Individually, so one 404 can't fail the whole install.
      await Promise.all(
        PRECACHE.map((url) =>
          cache.add(new Request(url, { cache: 'reload' })).catch(() => {}),
        ),
      );
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key !== CACHE) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);

      // Navigations: cache first so a dead connection is instant, then refresh
      // in the background for next time.
      if (request.mode === 'navigate') {
        const hit = await cache.match(request, { ignoreSearch: true });
        if (hit) {
          refresh(cache, request);
          return hit;
        }
        try {
          return await fetch(request);
        } catch {
          return (
            (await cache.match('/', { ignoreSearch: true })) ??
            new Response('Offline, and this page was never saved.', {
              status: 503,
              headers: { 'content-type': 'text/plain; charset=utf-8' },
            })
          );
        }
      }

      // Everything else is content-hashed or static: cache wins outright.
      const hit = await cache.match(request, { ignoreSearch: true });
      if (hit) return hit;

      try {
        const res = await fetch(request);
        if (res.ok && res.type === 'basic') cache.put(request, res.clone());
        return res;
      } catch {
        return new Response('', { status: 504 });
      }
    })(),
  );
});

function refresh(cache, request) {
  fetch(request)
    .then((res) => {
      if (res.ok) cache.put(request, res);
    })
    .catch(() => {});
}
`;

await writeFile(join(DIST, 'sw.js'), sw, 'utf8');

const mb = (bytes / 1024 / 1024).toFixed(2);
console.log(`sw.js: ${manifest.length} urls precached, ${mb} MB`);
