/**
 * Generates dist/sw.js after the Astro build.
 *
 * She opens this on ship wifi and then walks an island with no signal, so the
 * whole site is precached up front rather than lazily as she browses — a page
 * she never opened on wifi is a page she cannot open ashore.
 *
 * Shell and photos go in separate caches and the shell goes first: if the
 * photos fail or blow a quota, the site is still fully usable as text.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname;

/** Consumed by Cloudflare, or must never be served from cache. */
const EXCLUDE = new Set(['sw.js', '_headers', '_redirects', 'robots.txt']);

const SHELL_EXT = new Set(['.html', '.css', '.js', '.woff2', '.webmanifest', '.ico']);
const MEDIA_EXT = new Set(['.avif', '.webp', '.jpg', '.jpeg', '.png', '.svg', '.gif']);

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

const files = (await walk(DIST)).sort();

const shell = new Set();
const media = new Set();
let bytes = 0;

for (const f of files) {
  const rel = relative(DIST, f).split(sep).join('/');
  if (EXCLUDE.has(rel)) continue;
  const ext = rel.slice(rel.lastIndexOf('.'));

  if (SHELL_EXT.has(ext)) {
    // Register the clean URL she'll actually navigate to, not the index.html.
    if (rel === 'index.html') shell.add('/');
    else if (rel.endsWith('/index.html')) shell.add('/' + rel.slice(0, -'/index.html'.length));
    else shell.add('/' + rel);
  } else if (MEDIA_EXT.has(ext)) {
    media.add('/' + rel);
  } else {
    continue;
  }
  bytes += (await stat(f)).size;
}

// Content-addressed, so the cache only churns when something really changed.
const hash = createHash('sha256');
for (const f of files) hash.update(await readFile(f));
const version = hash.digest('hex').slice(0, 12);

const sw = `/* Generated by scripts/build-sw.mjs — do not edit by hand. */
const VERSION = ${JSON.stringify(version)};
const SHELL = 'shell-' + VERSION;
const MEDIA = 'media-' + VERSION;
const KEEP = [SHELL, MEDIA];

const PRECACHE_SHELL = ${JSON.stringify([...shell].sort())};
const PRECACHE_MEDIA = ${JSON.stringify([...media].sort())};

/**
 * Chunked and individually tolerant. A single 404 or QuotaExceededError must
 * never reject install — a worker that refuses to activate means zero offline,
 * which is far worse than a partial cache.
 */
async function precache(name, urls) {
  const cache = await caches.open(name);
  const CHUNK = 6;
  for (let i = 0; i < urls.length; i += CHUNK) {
    await Promise.all(
      urls.slice(i, i + CHUNK).map(async (url) => {
        try {
          const res = await fetch(
            new Request(url, { cache: 'reload', credentials: 'same-origin' }),
          );
          if (res.ok && res.type === 'basic') await cache.put(url, res);
        } catch {
          /* Skip it and keep going. */
        }
      }),
    );
  }
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      await precache(SHELL, PRECACHE_SHELL);
      await precache(MEDIA, PRECACHE_MEDIA);
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (!KEEP.includes(key)) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  // Safari issues Range requests for media; cache.match would hand back a
  // full 200 that the element rejects. Let the network handle those.
  if (request.headers.has('range')) return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    (async () => {
      // Navigations: serve from cache instantly, then refresh quietly for next
      // time. On a dead connection this is the whole point of the site.
      if (request.mode === 'navigate') {
        const cache = await caches.open(SHELL);
        const hit = await cache.match(request, { ignoreSearch: true });
        if (hit) {
          revalidate(cache, request);
          return hit;
        }
        try {
          return await fetch(request);
        } catch {
          return (
            (await cache.match('/', { ignoreSearch: true })) ??
            new Response(
              '<!doctype html><meta charset=utf-8><title>Offline</title>' +
                '<p style="font:1rem/1.5 system-ui;padding:2rem">' +
                'You are offline and this page was never saved. Try the home page.',
              { status: 503, headers: { 'content-type': 'text/html; charset=utf-8' } },
            )
          );
        }
      }

      // Everything else is either content-hashed or a photo: cache wins.
      for (const name of KEEP) {
        const cache = await caches.open(name);
        const hit = await cache.match(request, { ignoreSearch: true });
        if (hit) return hit;
      }

      try {
        const res = await fetch(request);
        if (res.ok && res.type === 'basic') {
          const name = /\\.(avif|webp|jpe?g|png|gif|svg)$/i.test(url.pathname) ? MEDIA : SHELL;
          const cache = await caches.open(name);
          cache.put(request, res.clone());
        }
        return res;
      } catch {
        return new Response('', { status: 504 });
      }
    })(),
  );
});

function revalidate(cache, request) {
  fetch(request)
    .then((res) => {
      if (res.ok && res.type === 'basic') cache.put(request, res);
    })
    .catch(() => {});
}
`;

await writeFile(join(DIST, 'sw.js'), sw, 'utf8');
console.log(
  `sw.js  shell:${shell.size}  media:${media.size}  ${(bytes / 1048576).toFixed(2)} MB  v${version}`,
);
